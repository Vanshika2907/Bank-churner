from __future__ import annotations

from typing import Dict, List

import streamlit as st

from src.model.predictor import FEATURE_GROUPS, load_predictor, predict_customer
from src.ui.components import render_explainability_panel, render_home, render_model_diagnostics, render_prediction_result
from src.utils.validation import validate_customer_payload


st.set_page_config(
    page_title="Bank Customer Relationship Exit Prediction",
    page_icon="🏦",
    layout="wide",
    initial_sidebar_state="expanded",
)


def field_widget(field: str, value: object = None) -> object:
    if field in {"age_band", "customer_segment", "primary_account_type", "relationship_status"}:
        options = {
            "age_band": ["18-25", "26-35", "36-45", "46-55", "56-65", "65+"],
            "customer_segment": ["Mass", "Mass Affluent", "Premium", "SME", "Wealth"],
            "primary_account_type": ["Current", "Savings", "Business", "Private"],
            "relationship_status": ["Primary", "Secondary"],
        }[field]
        return st.selectbox(field.replace("_", " ").title(), options, index=0)

    if field in {"number_of_active_products", "recent_overdraft_occurrences", "number_of_active_banking_channels", "complaint_occurrence", "failed_service_transaction_incidents", "branch_service_interaction_frequency", "service_interaction_frequency"}:
        return st.number_input(field.replace("_", " ").title(), min_value=0, max_value=100, value=2, step=1)

    if field == "customer_tenure":
        return st.number_input(field.replace("_", " ").title(), min_value=0.0, max_value=40.0, value=8.0, step=0.1)

    return st.number_input(field.replace("_", " ").title(), min_value=0.0, max_value=5000000.0, value=120000.0, step=1000.0)


def collect_step_payload(step_fields: List[str]) -> Dict[str, object]:
    payload: Dict[str, object] = {}
    for field in step_fields:
        payload[field] = field_widget(field)
    return payload


def render_home_page() -> None:
    render_home()


def render_prediction_page() -> None:
    st.header("Customer Exit Prediction")
    st.caption("The prediction is generated by the saved model pipeline; the form simply collects the raw inputs used by that pipeline.")

    if "customer_payload" not in st.session_state:
        st.session_state.customer_payload = {}

    step_order = list(FEATURE_GROUPS.keys())
    if "prediction_step_index" not in st.session_state:
        st.session_state.prediction_step_index = 0

    current_step = st.session_state.prediction_step_index
    step_name = step_order[current_step]
    step_fields = FEATURE_GROUPS[step_name]

    st.markdown(f"### Step {current_step + 1} of {len(step_order)}: {step_name}")
    st.progress((current_step + 1) / len(step_order))

    payload = st.session_state.customer_payload.copy()
    for field in step_fields:
        if field in payload:
            default_value = payload[field]
        else:
            default_value = None

        if field in {"age_band", "customer_segment", "primary_account_type", "relationship_status"}:
            options = {
                "age_band": ["18-25", "26-35", "36-45", "46-55", "56-65", "65+"],
                "customer_segment": ["Mass", "Mass Affluent", "Premium", "SME", "Wealth"],
                "primary_account_type": ["Current", "Savings", "Business", "Private"],
                "relationship_status": ["Primary", "Secondary"],
            }[field]
            payload[field] = st.selectbox(field.replace("_", " ").title(), options, index=options.index(default_value) if default_value in options else 0)
        elif field in {"number_of_active_products", "recent_overdraft_occurrences", "number_of_active_banking_channels", "complaint_occurrence", "failed_service_transaction_incidents", "branch_service_interaction_frequency", "service_interaction_frequency"}:
            payload[field] = st.number_input(field.replace("_", " ").title(), min_value=0, max_value=100, value=int(default_value) if default_value is not None else 2, step=1)
        elif field == "customer_tenure":
            payload[field] = st.number_input(field.replace("_", " ").title(), min_value=0.0, max_value=40.0, value=float(default_value) if default_value is not None else 8.0, step=0.1)
        else:
            payload[field] = st.number_input(field.replace("_", " ").title(), min_value=0.0, max_value=5000000.0, value=float(default_value) if default_value is not None else 120000.0, step=1000.0)

    st.session_state.customer_payload = payload

    col_prev, col_next, col_submit = st.columns([1, 1, 2])
    if current_step > 0:
        if col_prev.button("Back"):
            st.session_state.prediction_step_index = max(0, current_step - 1)
            st.rerun()

    if current_step < len(step_order) - 1:
        if col_next.button("Next"):
            st.session_state.prediction_step_index = current_step + 1
            st.rerun()
    else:
        if col_submit.button("Predict Relationship Exit", use_container_width=True):
            validation = validate_customer_payload(payload)
            if not validation["valid"]:
                for message in validation["errors"]:
                    st.error(message)
                return

            predictor = load_predictor()
            result = predict_customer(payload, predictor)
            st.session_state.last_prediction = result
            st.session_state.customer_payload = payload
            st.session_state.prediction_step_index = 0
            render_prediction_result(result)
            render_explainability_panel(result)


def main() -> None:
    st.sidebar.title("Project Overview")
    st.sidebar.caption("University ML project")
    st.sidebar.markdown("**Project:** Bank Customer Relationship Exit Prediction")
    st.sidebar.markdown("**Focus:** 6-month relationship exit risk")
    st.sidebar.markdown("**Data status:** Synthetic, academic use only")

    project_tab = st.sidebar.radio("Navigate", ["Home", "Prediction", "Diagnostics"])

    if project_tab == "Home":
        render_home_page()
    elif project_tab == "Prediction":
        render_prediction_page()
    else:
        render_model_diagnostics()


if __name__ == "__main__":
    main()
